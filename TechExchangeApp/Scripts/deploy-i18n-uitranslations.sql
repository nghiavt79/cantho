INSERT INTO dbo.UiTranslations([Key], Vi, En, AllowHtml, IsActive, Creator, Created)
SELECT s.k, s.vi, s.en, s.ah, 1, 'i18n-deploy', GETDATE()
FROM @s s
WHERE NOT EXISTS (SELECT 1 FROM dbo.UiTranslations t WHERE t.[Key] = s.k);
DECLARE @ins INT = @@ROWCOUNT;

-- 2) Bo sung ban dich En cho dong da co nhung con trong
UPDATE t SET t.En = s.en, t.Modified = GETDATE(), t.Modifier = 'i18n-deploy'
FROM dbo.UiTranslations t
JOIN @s s ON s.k = t.[Key]
WHERE (t.En IS NULL OR LTRIM(RTRIM(t.En)) = N'') AND s.en IS NOT NULL;
DECLARE @upd INT = @@ROWCOUNT;

COMMIT;

SELECT @ins AS Inserted, @upd AS EnFilled, (SELECT COUNT(*) FROM dbo.UiTranslations) AS TotalKeys;

